// tool name pattern -> preferred phrase index
const TOOL_MAP = [
  [/read|grep|glob|ls/, 1],
  [/edit|write|patch|apply/, 13],
  [/shell|bash|exec|run/, 9],
  [/test/, 5],
  [/web|search|fetch/, 6],
  [/task|subagent|agent/, 3],
];

export function toolIndex(tool) {
  if (!tool) return undefined;
  const t = String(tool).toLowerCase();
  for (const [re, i] of TOOL_MAP) if (re.test(t)) return i;
  return undefined;
}

export function createPhraseController({ minIntervalMs = 1500, random = Math.random } = {}) {
  let last = -1;
  let lastAt = 0;
  return {
    // Returns a phrase index to display now; may return `last` when throttled.
    pick(preferred, now) {
      if (preferred !== undefined && preferred !== last && now - lastAt >= minIntervalMs) {
        last = preferred;
        lastAt = now;
        return last;
      }
      if (now - lastAt < minIntervalMs) return last;
      let next = preferred;
      if (next === undefined || next === last) {
        do {
          next = Math.floor(random() * PHRASES.length);
        } while (PHRASES.length > 1 && next === last);
      }
      last = next;
      lastAt = now;
      return last;
    },
    reset() {
      last = -1;
      lastAt = 0;
    },
  };
}
